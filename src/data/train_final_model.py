from pathlib import Path
import time

import joblib
import pandas as pd

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
)
from sklearn.tree import DecisionTreeClassifier


# =========================================================
# Experiment configuration
# =========================================================

RANDOM_STATE = 42
K = 40
CCP_ALPHA = 0.0000413333


# =========================================================
# Input data
# =========================================================

TRAIN_X = Path(
    "data/processed/X_train_preprocessed.csv"
)

TRAIN_Y = Path(
    "data/processed/y_train.csv"
)

TEST_X = Path(
    "data/processed/X_test_preprocessed.csv"
)

TEST_Y = Path(
    "data/processed/y_test.csv"
)


# =========================================================
# Final locked feature set
#
# This file was generated by finalize_feature_selection.py
# using the full training data only.
#
# The held-out test set is not used during feature selection.
# =========================================================

FINAL_FEATURES = Path(
    "data/processed/final_selected_features.csv"
)


# =========================================================
# Output paths
# =========================================================

MODEL_DIR = Path("models")
RESULTS_DIR = Path("results")

MODEL_PATH = (
    MODEL_DIR /
    "final_pruned_decision_tree.joblib"
)

FEATURE_PATH = (
    MODEL_DIR /
    "final_selected_features.csv"
)

RESULTS_PATH = (
    RESULTS_DIR /
    "final_test_results.csv"
)


def main():

    # -----------------------------------------------------
    # Create output directories if required.
    # -----------------------------------------------------

    MODEL_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    RESULTS_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    # -----------------------------------------------------
    # Load training and test data.
    # -----------------------------------------------------

    print(
        "Loading training and test data..."
    )

    X_train = pd.read_csv(
        TRAIN_X
    )

    y_train = pd.read_csv(
        TRAIN_Y
    ).iloc[:, 0]

    X_test = pd.read_csv(
        TEST_X
    )

    y_test = pd.read_csv(
        TEST_Y
    ).iloc[:, 0]

    print(
        f"Training data: {X_train.shape}"
    )

    print(
        f"Test data: {X_test.shape}"
    )

    # -----------------------------------------------------
    # Load FINAL LOCKED feature list.
    #
    # This feature list was generated from the complete
    # training set by finalize_feature_selection.py.
    # -----------------------------------------------------

    print(
        "\nLoading final locked feature set..."
    )

    feature_table = pd.read_csv(
        FINAL_FEATURES
    )

    selected_features = (
        feature_table
        .sort_values("rank")
        .head(K)["feature"]
        .tolist()
    )

    # -----------------------------------------------------
    # Verify the expected number of features.
    # -----------------------------------------------------

    if len(selected_features) != K:
        raise ValueError(
            f"Expected {K} selected features, "
            f"but found {len(selected_features)}."
        )

    # -----------------------------------------------------
    # Verify that all selected features exist in both
    # training and test data.
    # -----------------------------------------------------

    missing_train_features = [
        feature
        for feature in selected_features
        if feature not in X_train.columns
    ]

    missing_test_features = [
        feature
        for feature in selected_features
        if feature not in X_test.columns
    ]

    if missing_train_features:
        raise ValueError(
            "Selected features missing from training data: "
            f"{missing_train_features}"
        )

    if missing_test_features:
        raise ValueError(
            "Selected features missing from test data: "
            f"{missing_test_features}"
        )

    # -----------------------------------------------------
    # Display selected feature count.
    # -----------------------------------------------------

    print(
        f"\nSelected features: "
        f"{len(selected_features)}"
    )

    print(
        "\nFinal selected feature list:"
    )

    for i, feature in enumerate(
        selected_features,
        start=1
    ):
        print(
            f"{i:02d}. {feature}"
        )

    # -----------------------------------------------------
    # Apply exactly the same feature set to training
    # and test data.
    # -----------------------------------------------------

    X_train_selected = X_train[
        selected_features
    ]

    X_test_selected = X_test[
        selected_features
    ]

    print(
        "\nSelected training shape: "
        f"{X_train_selected.shape}"
    )

    print(
        "Selected test shape: "
        f"{X_test_selected.shape}"
    )

    # -----------------------------------------------------
    # Save exact feature list used by the final model.
    # -----------------------------------------------------

    pd.DataFrame({
        "rank": range(
            1,
            len(selected_features) + 1
        ),
        "feature": selected_features
    }).to_csv(
        FEATURE_PATH,
        index=False
    )

    # -----------------------------------------------------
    # Train FINAL model on ALL training data.
    #
    # No test observations are used during training.
    # -----------------------------------------------------

    print(
        "\nTraining final pruned decision tree..."
    )

    model = DecisionTreeClassifier(
        criterion="gini",
        ccp_alpha=CCP_ALPHA,
        random_state=RANDOM_STATE
    )

    training_start = time.perf_counter()

    model.fit(
        X_train_selected,
        y_train
    )

    training_time = (
        time.perf_counter()
        - training_start
    )

    print(
        f"Training time: "
        f"{training_time:.4f} seconds"
    )

    print(
        f"Tree depth: "
        f"{model.get_depth()}"
    )

    print(
        f"Tree nodes: "
        f"{model.tree_.node_count}"
    )

    print(
        f"Tree leaves: "
        f"{model.get_n_leaves()}"
    )

    # -----------------------------------------------------
    # FINAL TEST EVALUATION
    #
    # Test labels are used only here for final evaluation.
    # -----------------------------------------------------

    print(
        "\nEvaluating on untouched test set..."
    )

    test_start = time.perf_counter()

    predictions = model.predict(
        X_test_selected
    )

    total_test_time = (
        time.perf_counter()
        - test_start
    )

    # -----------------------------------------------------
    # Classification metrics
    # -----------------------------------------------------

    accuracy = accuracy_score(
        y_test,
        predictions
    )

    precision = precision_score(
        y_test,
        predictions,
        zero_division=0
    )

    recall = recall_score(
        y_test,
        predictions,
        zero_division=0
    )

    f1 = f1_score(
        y_test,
        predictions,
        zero_division=0
    )

    cm = confusion_matrix(
        y_test,
        predictions
    )

    # -----------------------------------------------------
    # Per-sample host prediction latency.
    #
    # IMPORTANT:
    # This is Python/scikit-learn host inference time.
    # It is NOT embedded ESP32 latency.
    # -----------------------------------------------------

    latency_ms = (
        total_test_time
        / len(X_test_selected)
        * 1000
    )

    # -----------------------------------------------------
    # Serialize final model.
    #
    # IMPORTANT:
    # This is the serialized sklearn model size.
    # It is NOT ESP32 firmware flash usage.
    # -----------------------------------------------------

    joblib.dump(
        model,
        MODEL_PATH
    )

    model_size_bytes = (
        MODEL_PATH.stat().st_size
    )

    model_size_kb = (
        model_size_bytes / 1024
    )

    # -----------------------------------------------------
    # Save final results.
    # -----------------------------------------------------

    results = {
        "model": "DecisionTreeClassifier",
        "criterion": "gini",
        "k_features": K,
        "ccp_alpha": CCP_ALPHA,
        "random_state": RANDOM_STATE,

        "train_samples": len(
            X_train_selected
        ),

        "test_samples": len(
            X_test_selected
        ),

        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1": f1,

        "tree_depth": (
            model.get_depth()
        ),

        "tree_nodes": (
            model.tree_.node_count
        ),

        "tree_leaves": (
            model.get_n_leaves()
        ),

        "training_time_seconds": (
            training_time
        ),

        "test_prediction_time_seconds": (
            total_test_time
        ),

        "mean_test_latency_ms": (
            latency_ms
        ),

        "serialized_model_size_bytes": (
            model_size_bytes
        ),

        "serialized_model_size_kb": (
            model_size_kb
        ),

        "true_negative": int(
            cm[0, 0]
        ),

        "false_positive": int(
            cm[0, 1]
        ),

        "false_negative": int(
            cm[1, 0]
        ),

        "true_positive": int(
            cm[1, 1]
        ),
    }

    results_df = pd.DataFrame(
        [results]
    )

    results_df.to_csv(
        RESULTS_PATH,
        index=False
    )

    # -----------------------------------------------------
    # Print final report.
    # -----------------------------------------------------

    print(
        "\n========================================"
    )

    print(
        "FINAL TEST RESULTS"
    )

    print(
        "========================================"
    )

    print(
        f"Accuracy : {accuracy:.6f}"
    )

    print(
        f"Precision: {precision:.6f}"
    )

    print(
        f"Recall   : {recall:.6f}"
    )

    print(
        f"F1       : {f1:.6f}"
    )

    print(
        "\nConfusion matrix:"
    )

    print(
        cm
    )

    print(
        "\nTree structure:"
    )

    print(
        f"Depth : {model.get_depth()}"
    )

    print(
        f"Nodes : {model.tree_.node_count}"
    )

    print(
        f"Leaves: {model.get_n_leaves()}"
    )

    print(
        "\nTiming:"
    )

    print(
        f"Total test prediction time: "
        f"{total_test_time:.6f} s"
    )

    print(
        f"Mean latency per sample: "
        f"{latency_ms:.6f} ms"
    )

    print(
        "\nSerialized model:"
    )

    print(
        f"Size: {model_size_kb:.2f} KB"
    )

    print(
        "\nSaved:"
    )

    print(
        MODEL_PATH
    )

    print(
        FEATURE_PATH
    )

    print(
        RESULTS_PATH
    )


if __name__ == "__main__":
    main()
    